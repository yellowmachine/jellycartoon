// The documentation (#380), at docs.seilide.app: Starlight, a static site served by Caddy
// (Dockerfile). The family's guide (guia/, its screenshots by nube/scripts/capturas/, #495) and the
// technical part, from the READMEs.
import { rmSync } from 'node:fs';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';
// Gruvbox (2026-11-03), cálido y retro: elegido de momento, a falta de lo que diga la familia.
import starlightThemeGruvbox from 'starlight-theme-gruvbox';
import { createStarlightTypeDocPlugin } from 'starlight-typedoc';

// «Código»: the exported functions and their /** */ comments, read by TypeDoc. Only in local, with
// `bun run codigo` (CODIGO=1): the build for docs.seilide.app does not run it, and the generated
// pages (src/content/docs/codigo/) are not in git. Generated on each start, without the plugin's
// `watch`: its watch mode ignores skipErrorChecking and stops at types imported from .svelte files
// (svelte-check understands them, TypeScript alone does not), and with `astro build` it never ends.
const codigo = process.env.CODIGO === '1';
// Without CODIGO, the pages generated by an earlier `bun run codigo` would be built without their
// sidebar: they are removed.
if (!codigo)
	rmSync(new URL('./src/content/docs/codigo', import.meta.url), { recursive: true, force: true });
const [casaCodigo, casaCodigoGrupo] = createStarlightTypeDocPlugin();
const [comunCodigo, comunCodigoGrupo] = createStarlightTypeDocPlugin();
const [nubeCodigo, nubeCodigoGrupo] = createStarlightTypeDocPlugin();
const typeDoc = {
	entryPointStrategy: 'expand',
	exclude: ['**/*.test.ts', '**/*.spec.ts', '**/node_modules/**'],
	// The code is already checked by svelte-check; TypeDoc does not understand .svelte imports.
	skipErrorChecking: true,
	excludePrivate: true,
	// Each module's page as index.md, not README.md: starlight-typedoc drops those README.md pages when
	// there are several modules and no readme, but the list of modules still links to them.
	entryFileName: 'index'
};
const codigoPlugins = codigo
	? [
			casaCodigo({
				entryPoints: ['../src/lib'],
				tsconfig: '../tsconfig.json',
				output: 'codigo/casa',
				sidebar: { label: 'Casa (src/lib)', collapsed: true },
				// src/lib/index.ts is SvelteKit's empty placeholder: its page «index» would collide with
				// the group's own index.md.
				typeDoc: { ...typeDoc, exclude: [...typeDoc.exclude, '**/src/lib/index.ts'] }
			}),
			comunCodigo({
				entryPoints: ['../packages/comun/src'],
				tsconfig: '../tsconfig.json',
				output: 'codigo/comun',
				sidebar: { label: 'Común (packages/comun)', collapsed: true },
				typeDoc
			}),
			nubeCodigo({
				entryPoints: ['../nube/src/lib'],
				tsconfig: '../nube/tsconfig.json',
				output: 'codigo/seilide',
				sidebar: { label: 'Seilide (nube/src/lib)', collapsed: true },
				typeDoc
			})
		]
	: [];

